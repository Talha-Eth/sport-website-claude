/* Download the Barlow / Barlow Condensed woff2 files used by the
   site so the pages never wait on Google Fonts. Run once:
     node tools/fetch_fonts.js
*/
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const FONT_DIR = path.join(ROOT, "assets", "fonts");
const CSS_URL = "https://fonts.googleapis.com/css2?family=Barlow:wght@400;500;600;700&family=Barlow+Condensed:wght@600;700&display=swap";
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

async function main() {
  fs.mkdirSync(FONT_DIR, { recursive: true });
  const response = await fetch(CSS_URL, { headers: { "User-Agent": UA } });
  if (!response.ok) throw new Error(`CSS request failed: ${response.status}`);
  const css = await response.text();

  const blocks = [];
  const regex = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([\s\S]*?)\}/g;
  let match;
  while ((match = regex.exec(css))) {
    const subset = match[1];
    if (!["latin", "latin-ext"].includes(subset)) continue;
    const body = match[2];
    const family = /font-family:\s*'([^']+)'/.exec(body)?.[1];
    const weight = /font-weight:\s*(\d+)/.exec(body)?.[1];
    const style = /font-style:\s*(\w+)/.exec(body)?.[1] || "normal";
    const url = /url\((https:\/\/[^)]+\.woff2)\)/.exec(body)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
    if (!family || !weight || !url) continue;
    const file = `${family.replace(/\s+/g, "-")}-${weight}-${subset}.woff2`;
    blocks.push({ subset, family, weight, style, url, range, file });
  }

  if (!blocks.length) throw new Error("No font blocks parsed from Google CSS");

  for (const block of blocks) {
    const target = path.join(FONT_DIR, block.file);
    if (fs.existsSync(target)) continue;
    const font = await fetch(block.url, { headers: { "User-Agent": UA } });
    if (!font.ok) throw new Error(`Font request failed: ${block.url}`);
    const buffer = Buffer.from(await font.arrayBuffer());
    fs.writeFileSync(target, buffer);
    console.log(`saved ${block.file} (${buffer.length} bytes)`);
  }

  const cssOut = blocks.map((block) => `/* ${block.subset} */
@font-face {
  font-family: '${block.family}';
  font-style: ${block.style};
  font-weight: ${block.weight};
  font-display: swap;
  src: url('../fonts/${block.file}') format('woff2');
  unicode-range: ${block.range};
}`).join("\n\n");

  fs.writeFileSync(
    path.join(ROOT, "assets", "css", "fonts.css"),
    `/* Local Barlow / Barlow Condensed, generated by tools/fetch_fonts.js.
   Self-hosted so the site loads instantly and works offline. */\n\n${cssOut}\n`,
    "utf8"
  );
  console.log(`wrote ${blocks.length} @font-face rules to assets/css/fonts.css`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
